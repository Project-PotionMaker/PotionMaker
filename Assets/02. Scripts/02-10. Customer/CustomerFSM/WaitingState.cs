using UnityEngine;

public class WaitingState : BaseCustomerState
{
    public WaitingState(Customer owner) : base(owner)
    {
    }
    public override void EnterState()
    {
        base.EnterState();
    }
    public override void Update(float deltaTime)
    {
        base.Update(deltaTime);
    }
    public override void ExitState()
    {
        base.ExitState();
    }
}
